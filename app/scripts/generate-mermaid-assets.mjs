#!/usr/bin/env node
// Generates src/components/mermaid-assets.ts from the installed `mermaid`
// package: the minified UMD bundle inlined as a string constant. The native
// mermaid renderer embeds it in its WebView shell, so diagrams render offline
// with zero network fetches and no per-WebView CDN parse.
//
// Usage: npm run generate:mermaid-assets   (re-run after changing mermaid version)

import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(appRoot, "package.json"));

const mermaidPkgDir = path.dirname(require.resolve("mermaid/package.json"));
const mermaidVersion = JSON.parse(
  fs.readFileSync(path.join(mermaidPkgDir, "package.json"), "utf8"),
).version;

const minJsPath = path.join(mermaidPkgDir, "dist", "mermaid.min.js");
const minJs = fs.readFileSync(minJsPath, "utf8");
if (!minJs.includes("mermaid") || minJs.length < 1_000_000) {
  throw new Error("mermaid.min.js looks wrong; check the resolved package");
}

const header = `// AUTO-GENERATED by scripts/generate-mermaid-assets.mjs — do not edit.
// Source: mermaid@${mermaidVersion} dist/mermaid.min.js (${minJs.length} bytes).
// Re-run \`npm run generate:mermaid-assets\` after upgrading mermaid.
`;

const out = `${header}
export const MERMAID_VERSION = ${JSON.stringify(mermaidVersion)};

export const MERMAID_MIN_JS = ${JSON.stringify(minJs)};
`;

const target = path.join(appRoot, "src", "components", "mermaid-assets.ts");
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(appRoot, target)} (${out.length} bytes, mermaid ${mermaidVersion})`);
